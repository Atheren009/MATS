"""
SignalFilterLSTM — PyTorch LSTM model for Phase 1 confirmation.
Predicts N-bar forward log return sign to filter Phase 0 baseline signals.
"""

import logging
import pickle
from pathlib import Path
from typing import Optional

import numpy as np
import pandas as pd
import torch
import torch.nn as nn
import torch.optim as optim
from torch.utils.data import DataLoader as TorchDataLoader

from ..config import (
    LSTM_BATCH_SIZE,
    LSTM_DROPOUT,
    LSTM_EARLY_STOP,
    LSTM_EPOCHS,
    LSTM_HIDDEN_DIM,
    LSTM_LAYERS,
    LSTM_LEARNING_RATE,
    LSTM_SEQ_LEN,
    MODEL_DIR,
    detect_gpu,
)
from ..data.loader import TimeSeriesDataset

log = logging.getLogger(__name__)


class LSTMNet(nn.Module):
    def __init__(self, input_dim: int, hidden_dim: int, num_layers: int, dropout: float):
        super().__init__()
        self.lstm = nn.LSTM(
            input_size=input_dim,
            hidden_size=hidden_dim,
            num_layers=num_layers,
            batch_first=True,
            dropout=dropout if num_layers > 1 else 0.0,
        )
        self.fc = nn.Linear(hidden_dim, 1)
        self.sigmoid = nn.Sigmoid()

    def forward(self, x):
        # x shape: [batch, seq_len, input_dim]
        lstm_out, _ = self.lstm(x)
        # Take the output of the last time step
        last_out = lstm_out[:, -1, :]
        out = self.fc(last_out)
        return self.sigmoid(out).squeeze(-1)


class SignalFilterLSTM:
    """
    LSTM Wrapper that handles data preparation, training, and inference.
    """
    def __init__(self, symbol: str):
        self.symbol = symbol
        self.device = torch.device(detect_gpu()["device"])
        self.model: Optional[LSTMNet] = None
        self.feature_cols: list[str] = []
        
        # Scaling parameters (fitted during training)
        self.feature_means: Optional[np.ndarray] = None
        self.feature_stds: Optional[np.ndarray] = None

    def _scale_features(self, X: np.ndarray, fit: bool = False) -> np.ndarray:
        """Standardize features."""
        if fit:
            self.feature_means = np.nanmean(X, axis=0)
            self.feature_stds = np.nanstd(X, axis=0)
            self.feature_stds[self.feature_stds == 0] = 1.0  # Prevent div by zero
            
        return (X - self.feature_means) / self.feature_stds

    def fit(self, df_features: pd.DataFrame, val_split: float = 0.2):
        """
        Train the LSTM on the provided feature dataframe.
        df_features must include the 'target' column generated by DataLoader.compute_lstm_features.
        """
        if "target" not in df_features.columns:
            raise ValueError("Dataframe missing 'target' column.")
            
        self.feature_cols = [c for c in df_features.columns if c not in ["target", "session", "regime"]]
        
        # Prepare arrays
        X = df_features[self.feature_cols].values
        y = df_features["target"].values
        
        X_scaled = self._scale_features(X, fit=True)
        X_scaled = np.nan_to_num(X_scaled, nan=0.0)
        
        # Train / Validation Split (temporal)
        split_idx = int(len(X_scaled) * (1 - val_split))
        
        train_dataset = TimeSeriesDataset(X_scaled[:split_idx], y[:split_idx], LSTM_SEQ_LEN)
        val_dataset = TimeSeriesDataset(X_scaled[split_idx:], y[split_idx:], LSTM_SEQ_LEN)
        
        train_loader = TorchDataLoader(train_dataset, batch_size=LSTM_BATCH_SIZE, shuffle=False)
        val_loader = TorchDataLoader(val_dataset, batch_size=LSTM_BATCH_SIZE, shuffle=False)
        
        # Init model
        input_dim = len(self.feature_cols)
        self.model = LSTMNet(
            input_dim=input_dim,
            hidden_dim=LSTM_HIDDEN_DIM,
            num_layers=LSTM_LAYERS,
            dropout=LSTM_DROPOUT
        ).to(self.device)
        
        criterion = nn.BCELoss()
        optimizer = optim.Adam(self.model.parameters(), lr=LSTM_LEARNING_RATE)
        
        best_val_loss = float("inf")
        patience_counter = 0
        best_state = None
        
        log.info("Starting LSTM training for %s on %s...", self.symbol, self.device)
        
        for epoch in range(LSTM_EPOCHS):
            self.model.train()
            train_loss = 0.0
            
            for X_batch, y_batch in train_loader:
                X_batch, y_batch = X_batch.to(self.device), y_batch.to(self.device)
                
                optimizer.zero_grad()
                preds = self.model(X_batch)
                loss = criterion(preds, y_batch)
                loss.backward()
                optimizer.step()
                
                train_loss += loss.item() * X_batch.size(0)
                
            train_loss /= len(train_dataset)
            
            # Validation
            self.model.eval()
            val_loss = 0.0
            with torch.no_grad():
                for X_batch, y_batch in val_loader:
                    X_batch, y_batch = X_batch.to(self.device), y_batch.to(self.device)
                    preds = self.model(X_batch)
                    loss = criterion(preds, y_batch)
                    val_loss += loss.item() * X_batch.size(0)
                    
            val_loss /= len(val_dataset)
            
            log.debug("Epoch %d: Train Loss %.4f | Val Loss %.4f", epoch + 1, train_loss, val_loss)
            
            if val_loss < best_val_loss:
                best_val_loss = val_loss
                patience_counter = 0
                best_state = self.model.state_dict().copy()
            else:
                patience_counter += 1
                
            if patience_counter >= LSTM_EARLY_STOP:
                log.info("Early stopping triggered at epoch %d.", epoch + 1)
                break
                
        if best_state is not None:
            self.model.load_state_dict(best_state)
            
        log.info("LSTM training completed. Best Val Loss: %.4f", best_val_loss)

    def predict(self, df_features: pd.DataFrame) -> pd.Series:
        """
        Generate predictions for the given dataframe.
        Because of seq_len, the first seq_len - 1 bars will not have predictions.
        """
        if self.model is None:
            raise RuntimeError("LSTM not fitted.")
            
        self.model.eval()
        
        X = df_features[self.feature_cols].values
        X_scaled = self._scale_features(X, fit=False)
        X_scaled = np.nan_to_num(X_scaled, nan=0.0)
        
        # We need a dummy y to use the dataset class
        dummy_y = np.zeros(len(X_scaled))
        dataset = TimeSeriesDataset(X_scaled, dummy_y, LSTM_SEQ_LEN)
        loader = TorchDataLoader(dataset, batch_size=LSTM_BATCH_SIZE, shuffle=False)
        
        all_preds = []
        with torch.no_grad():
            for X_batch, _ in loader:
                X_batch = X_batch.to(self.device)
                preds = self.model(X_batch)
                all_preds.extend(preds.cpu().numpy())
                
        # Pad the beginning with NaN where we don't have enough history
        pad_len = LSTM_SEQ_LEN - 1
        padded_preds = [np.nan] * pad_len + all_preds
        
        return pd.Series(padded_preds, index=df_features.index, name="lstm_prob")

    def save(self, path: Optional[Path] = None) -> Path:
        if path is None:
            path = MODEL_DIR / f"lstm_{self.symbol}.pt"
        
        state = {
            "model_state": self.model.state_dict(),
            "feature_cols": self.feature_cols,
            "feature_means": self.feature_means,
            "feature_stds": self.feature_stds,
            "input_dim": len(self.feature_cols),
            "hidden_dim": LSTM_HIDDEN_DIM,
            "num_layers": LSTM_LAYERS,
            "dropout": LSTM_DROPOUT
        }
        torch.save(state, path)
        log.info("  LSTM saved -> %s", path)
        return path

    @classmethod
    def load(cls, symbol: str, path: Optional[Path] = None) -> "SignalFilterLSTM":
        if path is None:
            path = MODEL_DIR / f"lstm_{symbol}.pt"
            
        state = torch.load(path, map_location="cpu", weights_only=True)
        
        obj = cls(symbol)
        obj.feature_cols = state["feature_cols"]
        obj.feature_means = state["feature_means"]
        obj.feature_stds = state["feature_stds"]
        
        obj.model = LSTMNet(
            input_dim=state["input_dim"],
            hidden_dim=state["hidden_dim"],
            num_layers=state["num_layers"],
            dropout=state["dropout"]
        ).to(obj.device)
        
        obj.model.load_state_dict(state["model_state"])
        log.info("  LSTM loaded <- %s", path)
        return obj
